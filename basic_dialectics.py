def complete_worked_example():
    """
    Complete worked example of a dialectical process
    """
    print("\n" + "="*70)
    print("6. COMPLETE WORKED EXAMPLE")
    print("="*70)
    
    print("\n📖 Scenario: University Curriculum Reform")
    print("-"*50)
    
    # Define positions
    traditional_position = {
        'name': 'Traditional Curriculum',
        'values': [0.9, 0.8, 0.7, 0.3],  # [depth, structure, tradition, flexibility]
        'description': 'Emphasizes depth, structure, and established knowledge'
    }
    
    progressive_position = {
        'name': 'Progressive Curriculum',
        'values': [0.4, 0.3, 0.2, 0.9],  # [depth, structure, tradition, flexibility]
        'description': 'Emphasizes flexibility, interdisciplinary, and innovation'
    }
    
    print(f"\nThesis: {traditional_position['name']}")
    print(f"Values: Depth={traditional_position['values'][0]}, "
          f"Structure={traditional_position['values'][1]}, "
          f"Tradition={traditional_position['values'][2]}, "
          f"Flexibility={traditional_position['values'][3]}")
    print(f"Description: {traditional_position['description']}")
    
    print(f"\nAntithesis: {progressive_position['name']}")
    print(f"Values: Depth={progressive_position['values'][0]}, "
          f"Structure={progressive_position['values'][1]}, "
          f"Tradition={progressive_position['values'][2]}, "
          f"Flexibility={progressive_position['values'][3]}")
    print(f"Description: {progressive_position['description']}")
    
    # Calculate synthesis using different methods
    print("\n🔬 Calculating synthesis...")
    
    # Method 1: Simple average (standard synthesis)
    standard_synth = [
        (t + p) / 2 
        for t, p in zip(traditional_position['values'], progressive_position['values'])
    ]
    
    print(f"\nStandard synthesis (average):")
    print(f"  Depth: {standard_synth[0]:.2f}")
    print(f"  Structure: {standard_synth[1]:.2f}")
    print(f"  Tradition: {standard_synth[2]:.2f}")
    print(f"  Flexibility: {standard_synth[3]:.2f}")
    print("  → Balanced curriculum with moderate values")
    
    # Method 2: Emphasize common ground (geometric mean)
    geometric_synth = []
    for t, p in zip(traditional_position['values'], progressive_position['values']):
        if t * p > 0:  # Same sign
            geometric_synth.append(np.sqrt(abs(t * p)) * (1 if t >= 0 else -1))
        else:
            geometric_synth.append(0.0)
    
    print(f"\nGeometric synthesis (common ground):")
    print(f"  Depth: {geometric_synth[0]:.2f}")
    print(f"  Structure: {geometric_synth[1]:.2f}")
    print(f"  Tradition: {geometric_synth[2]:.2f}")
    print(f"  Flexibility: {geometric_synth[3]:.2f}")
    print("  → Emphasizes areas of agreement")
    
    # Method 3: Transform then blend (dialectical)
    transformed_traditional = list(reversed(traditional_position['values']))  # Apply R
    transformed_traditional = [-v for v in transformed_traditional]  # Apply N (gives C)
    
    dialectical_synth = [
        0.5 * tt + 0.5 * p
        for tt, p in zip(transformed_traditional, progressive_position['values'])
    ]
    
    print(f"\nDialectical synthesis (INRC transformed):")
    print(f"  Depth: {dialectical_synth[0]:.2f}")
    print(f"  Structure: {dialectical_synth[1]:.2f}")
    print(f"  Tradition: {dialectical_synth[2]:.2f}")
    print(f"  Flexibility: {dialectical_synth[3]:.2f}")
    print("  → Traditional values transformed then blended")
    
    # Negation of negation
    print("\n🌀 Negation of Negation (new thesis emerges):")
    print("The synthesis becomes a new thesis for further development")
    print("Example: 'Integrated Curriculum' that:")
    print("  • Maintains core disciplinary depth")
    print("  • Uses modular, flexible structure")
    print("  • Respects tradition while innovating")
    print("  • Balances structure with student choice")
    
    # Tension analysis
    print("\n📊 Tension Analysis:")
    differences = [abs(t - p) for t, p in zip(
        traditional_position['values'], progressive_position['values']
    )]
    tension_index = sum(differences) / (sum(traditional_position['values']) + 
                                       sum(progressive_position['values']))
    
    print(f"  Maximum difference: {max(differences):.2f} (Flexibility)")
    print(f"  Minimum difference: {min(differences):.2f} (Depth)")
    print(f"  Overall tension: {tension_index:.2f}")
    print(f"  → {'High' if tension_index > 0.6 else 'Moderate' if tension_index > 0.3 else 'Low'} dialectical tension")

