        ax[1].set_ylim(0, 1)
        ax[1].grid(True, alpha=0.3)
        ax[1].set_title('Dialectical Tension Evolution')
        ax[1].set_ylabel('Tension Index')
        ax[1].set_xlabel('Dialectical Stage')
        
        plt.tight_layout()
        plt.savefig('dialectical_process_visualization.png', dpi=150, bbox_inches='tight')
        print("✅ Visualization saved as 'dialectical_process_visualization.png'")
        print("   Left: Vector positions in 2D space")
        print("   Right: Tension evolution through stages")
        
